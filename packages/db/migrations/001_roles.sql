\set ON_ERROR_STOP on

SELECT format(
  'CREATE ROLE backlog_owner LOGIN PASSWORD %L NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION BYPASSRLS NOINHERIT',
  :'owner_password'
)
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'backlog_owner')
\gexec

SELECT format(
  'ALTER ROLE backlog_owner WITH LOGIN PASSWORD %L NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION BYPASSRLS NOINHERIT',
  :'owner_password'
)
\gexec

