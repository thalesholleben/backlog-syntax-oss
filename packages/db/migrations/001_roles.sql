REVOKE ALL ON DATABASE :"database_name" FROM PUBLIC;
GRANT CONNECT, CREATE, TEMPORARY ON DATABASE :"database_name" TO backlog_owner;
GRANT CONNECT ON DATABASE :"database_name" TO backlog_auth, backlog_app;
